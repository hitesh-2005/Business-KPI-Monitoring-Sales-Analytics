"""
Unit Tests for KPI Engine & Analytical SQL
===========================================
Validates mathematical correctness of:
- Bounded Order Return Rates (0–100%)
- Continuous calendar generation across missing dates
- True 7-day rolling averages
- Division by zero safety
"""

import pandas as pd
import pytest

from analytics.kpi_engine import load_sql_queries


def test_order_return_rate_bounded(in_memory_db):
    """Test that multiple returned line items within the same order do NOT produce return rates > 100%."""
    queries = load_sql_queries()
    pop_query = queries["POPULATE_DAILY_KPIS"]

    df = pd.read_sql_query(pop_query, in_memory_db, parse_dates=["kpi_date"])

    # On 2014-01-01:
    # 2 orders placed (ORD-101 with 2 items, ORD-102 with 1 item).
    # ORD-101 has 2 returned lines, ORD-102 has 0 returned lines.
    # Total returned orders = 1. Distinct orders = 2.
    # Order Return Rate must equal exactly 50.0% (NOT 100% or 200%).
    day_1 = df[df["kpi_date"] == "2014-01-01"].iloc[0]
    assert day_1["orders"] == 2
    assert day_1["returned_orders"] == 1
    assert day_1["returned_items"] == 2
    assert day_1["order_return_rate"] == 50.0
    assert 0.0 <= day_1["order_return_rate"] <= 100.0


def test_continuous_calendar_gap_filling(in_memory_db):
    """Test that dates with zero sales are generated by recursive calendar CTE and zero-filled."""
    queries = load_sql_queries()
    pop_query = queries["POPULATE_DAILY_KPIS"]

    df = pd.read_sql_query(pop_query, in_memory_db, parse_dates=["kpi_date"])

    # Span is 2014-01-01 to 2014-01-03 = 3 days
    assert len(df) == 3
    dates = [d.strftime("%Y-%m-%d") for d in df["kpi_date"]]
    assert dates == ["2014-01-01", "2014-01-02", "2014-01-03"]

    # 2014-01-02 had no transactions
    day_gap = df[df["kpi_date"] == "2014-01-02"].iloc[0]
    assert day_gap["revenue"] == 0.0
    assert day_gap["profit"] == 0.0
    assert day_gap["orders"] == 0
    assert day_gap["order_return_rate"] == 0.0
    assert day_gap["is_active_day"] == 0


def test_rolling_7day_average(in_memory_db):
    """Test rolling 7-day average computation over continuous calendar series."""
    queries = load_sql_queries()
    pop_query = queries["POPULATE_DAILY_KPIS"]

    df = pd.read_sql_query(pop_query, in_memory_db, parse_dates=["kpi_date"])

    # Day 1 revenue: 500 + 50 + 300 = 850.00
    # Day 2 revenue: 0.00
    # Day 3 revenue: 100.00
    # Day 1 rolling avg: 850.0 / 1 = 850.00
    # Day 2 rolling avg: (850 + 0) / 2 = 425.00
    # Day 3 rolling avg: (850 + 0 + 100) / 3 = 316.67
    assert df.loc[df["kpi_date"] == "2014-01-01", "revenue_7d_avg"].iloc[0] == 850.0
    assert df.loc[df["kpi_date"] == "2014-01-02", "revenue_7d_avg"].iloc[0] == 425.0
    assert df.loc[df["kpi_date"] == "2014-01-03", "revenue_7d_avg"].iloc[0] == 316.67


def test_sales_weighted_discount(in_memory_db):
    """Test that discount rate is weighted by sales volume rather than naive line average."""
    queries = load_sql_queries()
    pop_query = queries["POPULATE_DAILY_KPIS"]

    df = pd.read_sql_query(pop_query, in_memory_db, parse_dates=["kpi_date"])

    # On 2014-01-01:
    # Item 1: sales=500, discount=0.10 -> 50.0
    # Item 2: sales=50,  discount=0.00 -> 0.0
    # Item 3: sales=300, discount=0.20 -> 60.0
    # Total sales = 850. Total discount dollars = 110.0
    # Weighted discount pct = 110 / 850 * 100 = 12.94%
    day_1 = df[df["kpi_date"] == "2014-01-01"].iloc[0]
    assert day_1["weighted_discount"] == 12.94
